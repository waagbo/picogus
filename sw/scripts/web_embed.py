#!/usr/bin/env python3
"""Embed the web UI into the firmware as a gzip-compressed C array.

usage: web_embed.py <index.html> <output header>

The page is served with "Content-Encoding: gzip" and kept in flash: PicoGUS
firmware runs entirely from RAM, which is better spent on the sound card.
"""

import gzip
import sys


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = argv[1], argv[2]
    with open(src, "rb") as f:
        text = f.read().decode("utf-8")
    # Light minification that is safe for HTML, CSS and JS alike: drop
    # indentation and blank lines. gzip takes care of the rest.
    lines = [line.strip() for line in text.splitlines()]
    data = "\n".join(line for line in lines if line).encode("utf-8")
    # mtime=0 keeps builds reproducible
    gz = gzip.compress(data, compresslevel=9, mtime=0)
    out = [
        "// Generated by scripts/web_embed.py from www/index.html - do not edit",
        "#pragma once",
        "#include <stdint.h>",
        '#include "pico.h"',
        f"// {len(data)} bytes uncompressed",
        f"static const uint32_t web_index_html_gz_len = {len(gz)};",
        "// in flash: only read while web_task() holds off core 0 flash writes",
        'static const uint8_t __in_flash("web_ui") web_index_html_gz[] = {',
    ]
    for i in range(0, len(gz), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ",")
    out.append("};")
    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
